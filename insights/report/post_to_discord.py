#!/usr/bin/env python3
"""Post the daily usage report to #usage: image + embed + caption, one message.
Reads artifacts from report/out/ generated by report/build_report.py.
Usage: python3 post_to_discord.py
"""
import json, os, re, sys, uuid, urllib.request, urllib.error

raw = open(os.path.expanduser('~/.hermes/.env')).read()
tok = re.search(r'DISCORD_BOT_TOKEN=(.*)', raw).group(1).strip()
BASE = "https://discord.com/api/v10"
UA = {"Authorization": f"Bot {tok}", "User-Agent": "C6 usage bot (discord, 1.0)"}
CH = "1555760017293054034"  # #usage
OUT = os.path.expanduser('~/HydrocarbonForge/Projects/insights-board/report/out')
PNG = os.path.join(OUT, 'usage-report.png')
EMBED = os.path.join(OUT, 'embed.json')

caption = ""
embeds = []
if os.path.exists(EMBED):
    embed = json.load(open(EMBED))
    embed.pop("image", None)  # C6 attaches the PNG as the message image
    embeds = [embed]

payload = {"embeds": embeds}
if caption:
    payload["content"] = caption

boundary = uuid.uuid4().hex
body = b''
body += (f'--{boundary}\r\nContent-Disposition: form-data; name="payload_json"\r\n\r\n').encode()
body += json.dumps(payload).encode() + b'\r\n'
with open(PNG, 'rb') as f:
    fb = f.read()
body += (f'--{boundary}\r\nContent-Disposition: form-data; name="files[0]"; filename="usage-report.png"\r\nContent-Type: image/png\r\n\r\n').encode()
body += fb
body += f'\r\n--{boundary}--\r\n'.encode()

r = urllib.request.Request(f"{BASE}/channels/{CH}/messages", data=body, method='POST',
    headers={"Authorization": f"Bot {tok}", "User-Agent": "C6 usage bot (discord, 1.0)",
             "Content-Type": f"multipart/form-data; boundary={boundary}"})
try:
    with urllib.request.urlopen(r, timeout=20) as resp:
        d = json.loads(resp.read())
        print("POSTED id=", d['id'])
except urllib.error.HTTPError as e:
    print("HTTP", e.code, e.read().decode()[:300])
